-- #363 정산 실행에서 건너뛴 판매자 기록. job_execution_id는 settlement.BATCH_JOB_EXECUTION의 실행 ID(runId)다.
CREATE TABLE settlement.settlement_skip (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_execution_id bigint NOT NULL,
    seller_id bigint NOT NULL,
    phase character varying(20) NOT NULL,
    reason character varying(200) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT settlement_skip_phase_check CHECK (((phase)::text = ANY ((ARRAY['PROCESS'::character varying, 'WRITE'::character varying])::text[])))
);

CREATE INDEX idx_settlement_skip_job_execution_id ON settlement.settlement_skip (job_execution_id);
