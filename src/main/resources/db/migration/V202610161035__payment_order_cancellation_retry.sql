-- 처리하다 실패한 주문 취소(order.cancelled). 결제 스케줄러가 다시 처리하고, 성공하면 지운다 (#350)
CREATE TABLE payment.order_cancellation_retry (
    attempt_count integer NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    last_failed_at timestamp(6) without time zone NOT NULL,
    member_id bigint NOT NULL,
    order_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    last_error character varying(500),
    reason character varying(255),
    CONSTRAINT order_cancellation_retry_pkey PRIMARY KEY (id),
    CONSTRAINT order_cancellation_retry_order_id_key UNIQUE (order_id)
);
