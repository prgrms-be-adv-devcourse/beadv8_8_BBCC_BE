-- 알림 도메인: 보낼 알림 한 건 = 채널 하나. 같은 이벤트 · 같은 채널은 한 건만 (#392)
-- 채널 · 유형 · 상태는 단계마다 값이 늘어나므로 CHECK 제약을 두지 않는다
CREATE SCHEMA IF NOT EXISTS notification;

CREATE TABLE notification.notification (
    attempt_count integer NOT NULL,
    claimed_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    event_id uuid NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    member_id bigint NOT NULL,
    next_attempt_at timestamp(6) without time zone,
    sent_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone NOT NULL,
    version bigint NOT NULL,
    channel character varying(16) NOT NULL,
    status character varying(16) NOT NULL,
    type character varying(32) NOT NULL,
    recipient character varying(320),
    title character varying(255) NOT NULL,
    last_error character varying(500),
    body character varying(4000) NOT NULL,
    CONSTRAINT notification_pkey PRIMARY KEY (id),
    CONSTRAINT uk_notification_event_id_channel UNIQUE (event_id, channel)
);

-- 재시도 스케줄러가 상태와 다음 시도 시각으로 찾는다
CREATE INDEX idx_notification_status_next_attempt_at
    ON notification.notification USING btree (status, next_attempt_at);
