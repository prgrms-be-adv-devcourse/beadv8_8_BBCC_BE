-- #449 받은 이벤트(재고 차감됨 · 재고 차감 실패 · 결제 실패) 처리 실패 보관: (주문, 이벤트 종류)당 1건,
-- 재고 차감 실패의 주문상품별 사유는 자식 테이블. 기존 payment_recovery는 바꾸지 않는다.
-- 주문 FK는 두지 않는다(payment_recovery와 같음): 기록은 리스너 트랜잭션이 주문 행을 바꾼 채 열려 있을 때 다른 트랜잭션에서
-- 저장되므로, 주문 행 잠금과 엮일 여지를 없앤다. (주문, 종류)당 1건은 유니크로 지킨다.
CREATE TABLE orders.order_event_failure (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type character varying(30) NOT NULL,
    order_id bigint NOT NULL,
    status character varying(20) NOT NULL,
    failure_code character varying(100) NOT NULL,
    attempt_count integer NOT NULL,
    last_attempted_at timestamp(6) without time zone NOT NULL,
    version bigint,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT order_event_failure_event_type_check CHECK (((event_type)::text = ANY ((ARRAY[
        'STOCK_DEDUCTED'::character varying, 'STOCK_DEDUCTION_FAILED'::character varying,
        'PAYMENT_FAILED'::character varying])::text[]))),
    CONSTRAINT order_event_failure_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying,
        'RECOVERED'::character varying, 'CANCELLED'::character varying])::text[])))
);

CREATE UNIQUE INDEX uk_order_event_failure_order_event ON orders.order_event_failure USING btree (order_id, event_type);

CREATE INDEX idx_order_event_failure_status ON orders.order_event_failure USING btree (status);

CREATE TABLE orders.order_event_failure_item (
    order_event_failure_id bigint NOT NULL,
    order_item_id bigint NOT NULL,
    reason character varying(50) NOT NULL,
    CONSTRAINT fk_order_event_failure_item_failure FOREIGN KEY (order_event_failure_id)
        REFERENCES orders.order_event_failure(id)
);
