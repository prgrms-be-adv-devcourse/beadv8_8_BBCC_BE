-- 커뮤니티 활동 기록(#1128, append-only). 리뷰 · 찜 · 검사 · 작성 자격에서 생긴 사실을 원래 변경과 같은 트랜잭션에서 한 행씩 남긴다.
-- type은 활동 종류(ActivityType 이름), attributes는 type별 속성(키는 ActivityAttribute). 회원 ID · 닉네임 · 본문 · 사진 주소는 넣지 않는다.
-- 새 사실을 더해도 표 구조가 바뀌지 않게 FK · CHECK · 업무 유일 제약을 두지 않는다. 행을 고치거나 지우는 코드는 없다(보관 · 정리는 따로 정한다)
-- 이미 표가 있는 DB(공유 로컬)에서도 실패하지 않게 IF NOT EXISTS로 만든다
CREATE TABLE IF NOT EXISTS community.activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    occurred_at timestamp(6) without time zone NOT NULL,
    type character varying(40) NOT NULL,
    product_id bigint,
    aggregate_id bigint NOT NULL,
    attributes jsonb NOT NULL DEFAULT '{}',
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT activity_pkey PRIMARY KEY (id)
);

-- 기간별로 읽는다(시각 · id 순)
CREATE INDEX IF NOT EXISTS idx_activity_occurred_at ON community.activity (occurred_at, id);

-- 백필: 기록을 시작하기 전부터 있던 사실 중 지금 원본이 남아 있는 것만 원본 시각으로 한 번 넣는다(attributes.backfilled = true).
-- 같은 type · 대상 행이 이미 있으면 넣지 않아 다시 돌려도 중복이 없다. 이미 지워진 리뷰 · 찜, 과거 수정, 통과(PASSED) 결정은 원본이 없어 넣지 않는다
INSERT INTO community.activity (occurred_at, type, product_id, aggregate_id, attributes, created_at)
SELECT e.created_at, 'ELIGIBILITY_CREATED', e.product_id, e.id,
       jsonb_build_object('order_item_id', e.order_item_id, 'backfilled', true), LOCALTIMESTAMP
FROM community.review_eligibility e
WHERE NOT EXISTS (SELECT 1 FROM community.activity a WHERE a.type = 'ELIGIBILITY_CREATED' AND a.aggregate_id = e.id);

INSERT INTO community.activity (occurred_at, type, product_id, aggregate_id, attributes, created_at)
SELECT r.created_at, 'REVIEW_CREATED', r.product_id, r.id,
       jsonb_build_object('order_item_id', r.order_item_id, 'rating', r.rating, 'fit', r.fit,
           'image_count', (SELECT count(*) FROM community.review_image i WHERE i.review_id = r.id), 'backfilled', true),
       LOCALTIMESTAMP
FROM community.review r
WHERE NOT EXISTS (SELECT 1 FROM community.activity a WHERE a.type = 'REVIEW_CREATED' AND a.aggregate_id = r.id);

INSERT INTO community.activity (occurred_at, type, product_id, aggregate_id, attributes, created_at)
SELECT f.created_at, 'FAVORITE_ADDED', f.product_id, f.id, jsonb_build_object('backfilled', true), LOCALTIMESTAMP
FROM community.favorite f
WHERE NOT EXISTS (SELECT 1 FROM community.activity a WHERE a.type = 'FAVORITE_ADDED' AND a.aggregate_id = f.id);

INSERT INTO community.activity (occurred_at, type, product_id, aggregate_id, attributes, created_at)
SELECT r.moderated_at, 'MODERATION_DECIDED', r.product_id, r.id,
       -- 결정한 쪽은 상태로 정한다: 숨김 확정 · 다시 공개는 관리자만, 검사 숨김(HIDDEN)은 검사기만 만든다
       -- (moderated_by_admin_id는 글을 고쳐 다시 검사 대기가 되어도 남으므로 판정에 쓰지 않는다)
       jsonb_build_object('by', CASE WHEN r.moderation_status IN ('CONFIRMED_HIDDEN', 'RESTORED') THEN 'admin'
           ELSE 'moderator' END,
           'status', r.moderation_status, 'reason', r.moderation_reason, 'backfilled', true),
       LOCALTIMESTAMP
FROM community.review r
WHERE r.moderation_status NOT IN ('PASSED', 'PENDING')
  AND r.moderated_at IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM community.activity a WHERE a.type = 'MODERATION_DECIDED' AND a.aggregate_id = r.id);
