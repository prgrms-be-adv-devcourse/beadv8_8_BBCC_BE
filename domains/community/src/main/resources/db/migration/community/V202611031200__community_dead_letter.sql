-- #741 Kafka 보존 기간과 무관하게 커뮤니티 DLT 원본을 보관한다.
CREATE TABLE community.dead_letter (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dlt_topic varchar(150) NOT NULL,
    dlt_partition integer NOT NULL,
    dlt_offset bigint NOT NULL,
    source_topic varchar(100) NOT NULL,
    source_partition integer,
    source_offset bigint,
    message_key varchar(100),
    event_type varchar(100),
    event_id varchar(100),
    payload bytea,
    failure_type varchar(255),
    state varchar(20) NOT NULL DEFAULT 'OPEN',
    replay_count integer NOT NULL DEFAULT 0,
    last_replayed_by bigint,
    last_replayed_at timestamp(6) without time zone,
    last_replay_failure_type varchar(255),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_community_dead_letter_position UNIQUE (dlt_topic, dlt_partition, dlt_offset),
    CONSTRAINT community_dead_letter_state_check CHECK (state IN ('OPEN', 'REPROCESSED')),
    CONSTRAINT community_dead_letter_replay_count_check CHECK (replay_count >= 0)
);
CREATE INDEX idx_community_dead_letter_state_id ON community.dead_letter (state, id DESC);
