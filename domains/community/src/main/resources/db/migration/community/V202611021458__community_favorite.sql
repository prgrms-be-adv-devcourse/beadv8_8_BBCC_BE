-- 찜((회원, 상품)당 1개)
CREATE TABLE community.favorite (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    member_id bigint NOT NULL,
    product_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT favorite_pkey PRIMARY KEY (id),
    CONSTRAINT uk_favorite_member_product UNIQUE (member_id, product_id)
);

-- 내 찜 목록(최신순 커서)
CREATE INDEX idx_favorite_member_created ON community.favorite (member_id, created_at DESC, id DESC);

-- 상품별 찜 수. 증가는 INSERT … ON CONFLICT DO UPDATE, 감소는 UPDATE 한 문장
CREATE TABLE community.favorite_stats (
    product_id bigint NOT NULL,
    favorite_count bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT favorite_stats_pkey PRIMARY KEY (product_id),
    CONSTRAINT ck_favorite_stats_non_negative CHECK (favorite_count >= 0)
);
