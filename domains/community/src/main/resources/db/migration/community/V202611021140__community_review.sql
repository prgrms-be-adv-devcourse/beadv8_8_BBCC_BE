-- 리뷰(주문상품당 1개). 작성자 닉네임은 작성 시점 값을 저장한다
CREATE TABLE community.review (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    order_item_id bigint NOT NULL,
    product_id bigint NOT NULL,
    member_id bigint NOT NULL,
    nickname character varying(255),
    rating smallint NOT NULL,
    content character varying(1000) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT review_pkey PRIMARY KEY (id),
    CONSTRAINT uk_review_order_item_id UNIQUE (order_item_id),
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5)
);

-- 상품별 리뷰 목록 · 내 리뷰 목록(최신순 커서)
CREATE INDEX idx_review_product_created ON community.review (product_id, created_at DESC, id DESC);
CREATE INDEX idx_review_member_created ON community.review (member_id, created_at DESC, id DESC);

-- 상품별 리뷰 집계. 증감은 한 문장(INSERT … ON CONFLICT DO UPDATE)으로 한다
CREATE TABLE community.review_stats (
    product_id bigint NOT NULL,
    review_count bigint NOT NULL,
    rating_sum bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT review_stats_pkey PRIMARY KEY (product_id),
    CONSTRAINT ck_review_stats_non_negative CHECK (review_count >= 0 AND rating_sum >= 0)
);
