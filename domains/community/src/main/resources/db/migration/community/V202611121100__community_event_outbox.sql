-- 커뮤니티 이벤트 아웃박스(#1274). 리뷰 · 찜이 바뀐 트랜잭션에서 보낼 메시지(본문 JSON 완성본)를 함께 넣고, 릴레이가 커밋된 행을
-- id 순으로 kidly.community.events에 보낸 뒤 바로 지운다. 실패하면 시도 횟수 · 다음 시각을 미루고, 상한에 닿으면 격리(quarantined_at)한다.
-- 격리 행은 남겨 운영에서 본다. 이미 표가 있는 DB(공유 로컬)에서도 실패하지 않게 IF NOT EXISTS로 만든다
CREATE TABLE IF NOT EXISTS community.event_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id uuid NOT NULL,
    event_type character varying(60) NOT NULL,
    message_key character varying(40) NOT NULL,
    payload text NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamp(6) without time zone NOT NULL,
    last_failure_type character varying(200),
    quarantined_at timestamp(6) without time zone,
    CONSTRAINT event_outbox_pkey PRIMARY KEY (id),
    CONSTRAINT uk_event_outbox_event_id UNIQUE (event_id),
    CONSTRAINT ck_event_outbox_attempts CHECK (attempts >= 0)
);

-- 릴레이가 보낼 차례인 행(격리되지 않은 것)을 id 순으로 읽는다
CREATE INDEX IF NOT EXISTS idx_event_outbox_pending ON community.event_outbox (id) WHERE quarantined_at IS NULL;
