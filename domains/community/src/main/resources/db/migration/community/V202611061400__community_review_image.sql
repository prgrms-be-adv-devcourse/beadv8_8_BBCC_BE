-- 리뷰 사진(리뷰당 순서 있는 목록). 사진 주소는 업로드 주소 발급으로 올린 공개 주소다
-- 리뷰를 지우면 사진 행도 함께 지워진다(ON DELETE CASCADE). 같은 리뷰의 같은 순서는 하나다
-- 유일 제약 (review_id, position)의 인덱스가 review_id로 시작해 리뷰별 사진 조회에도 쓰인다
-- 이미 표가 있는 DB(공유 로컬)에서도 실패하지 않게 IF NOT EXISTS로 만든다
CREATE TABLE IF NOT EXISTS community.review_image (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    review_id bigint NOT NULL,
    position smallint NOT NULL,
    image_url character varying(500) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT review_image_pkey PRIMARY KEY (id),
    CONSTRAINT fk_review_image_review FOREIGN KEY (review_id) REFERENCES community.review (id) ON DELETE CASCADE,
    CONSTRAINT uk_review_image_review_position UNIQUE (review_id, position),
    CONSTRAINT ck_review_image_position CHECK (position >= 0)
);
