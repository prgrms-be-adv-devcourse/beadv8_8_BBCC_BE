-- 리뷰 작성 자격(주문상품당 1행). 주문상품 구매확정(order-item.purchase-confirmed)을 받아 만든다
CREATE TABLE community.review_eligibility (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    order_item_id bigint NOT NULL,
    order_id bigint,
    member_id bigint NOT NULL,
    product_id bigint NOT NULL,
    option_id bigint,
    size character varying(255),
    confirmed_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT review_eligibility_pkey PRIMARY KEY (id),
    CONSTRAINT uk_review_eligibility_order_item_id UNIQUE (order_item_id)
);

-- 내 자격 목록: 구매확정 최신순 커서
CREATE INDEX idx_review_eligibility_member_confirmed
    ON community.review_eligibility (member_id, confirmed_at DESC, id DESC);
