-- 리뷰 사진 정리 대기(#1036). 리뷰 수정으로 빠진 사진 · 리뷰 삭제로 남은 사진의 저장소 key를 수정 · 삭제 트랜잭션에서 남기고,
-- 정리 스케줄러가 next_attempt_at이 지난 행을 저장소에서 지운 뒤 행을 지운다. 실패하면 시도 +1 · 다음 시각을 미룬다(상한 없음)
-- 같은 key는 한 행이다(넣을 때 ON CONFLICT DO NOTHING으로 "이미 대기"에 수렴)
-- 이미 표가 있는 DB(공유 로컬)에서도 실패하지 않게 IF NOT EXISTS로 만든다
CREATE TABLE IF NOT EXISTS community.review_image_cleanup (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    object_key character varying(500) NOT NULL,
    reason character varying(20) NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamp(6) without time zone NOT NULL,
    last_failure_type character varying(200),
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT review_image_cleanup_pkey PRIMARY KEY (id),
    CONSTRAINT uk_review_image_cleanup_object_key UNIQUE (object_key),
    CONSTRAINT ck_review_image_cleanup_reason CHECK (reason IN ('REPLACED', 'REVIEW_DELETED')),
    CONSTRAINT ck_review_image_cleanup_attempts CHECK (attempts >= 0)
);

-- 처리할 차례인 행을 시각 · id 순으로 읽는다
CREATE INDEX IF NOT EXISTS idx_review_image_cleanup_next_attempt
    ON community.review_image_cleanup (next_attempt_at, id);

-- 지우기 직전 · 훑기에서 "지금 리뷰에 붙어 있는지"를 사진 주소로 찾는다
CREATE INDEX IF NOT EXISTS idx_review_image_image_url ON community.review_image (image_url);
