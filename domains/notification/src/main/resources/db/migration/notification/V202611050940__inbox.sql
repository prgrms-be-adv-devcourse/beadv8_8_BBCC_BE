-- 알림함: 회원이 사이트에서 보는 알림 한 건 (#852)
-- 제목 · 본문은 넣을 때 완성해 저장한다. 같은 일로 두 번 넣지 않게 dedup_key를 유일로 둔다
-- 유형은 단계마다 값이 늘어나므로 CHECK 제약을 두지 않는다
CREATE TABLE notification.inbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    member_id bigint NOT NULL,
    type character varying(32) NOT NULL,
    title character varying(255) NOT NULL,
    body character varying(1000) NOT NULL,
    link_path character varying(500),
    dedup_key character varying(200) NOT NULL,
    read_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT inbox_pkey PRIMARY KEY (id),
    CONSTRAINT uk_inbox_dedup_key UNIQUE (dedup_key)
);

-- 내 알림 최신순 목록
CREATE INDEX idx_inbox_member_id_created_at ON notification.inbox (member_id, created_at DESC);

-- 안 읽은 알림 개수
CREATE INDEX idx_inbox_member_id_unread ON notification.inbox (member_id) WHERE read_at IS NULL;
