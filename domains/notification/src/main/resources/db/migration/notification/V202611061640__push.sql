-- 웹 푸시(FCM). 알림 한 건 = 채널 하나 구조에 PUSH 채널을 더한다
-- 푸시는 누르면 이동할 화면 경로가 필요하다. 이메일은 쓰지 않아 비어 있다
ALTER TABLE notification.notification ADD COLUMN link_path character varying(500);

-- 회원의 브라우저별 FCM 대상 식별값 FID(Firebase Installation ID). 사이트에 들어올 때 등록하고, 로그아웃 · 탈퇴 · FCM 무효 응답 · 오래됨(270일) 때 지운다. 테이블 이름은 기획서대로 push_token
-- 같은 브라우저에 다른 회원이 로그인하면 같은 FID의 주인을 바꾼다(FID 유일)
CREATE TABLE notification.push_token (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    member_id bigint NOT NULL,
    fid character varying(1024) NOT NULL,
    last_registered_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT push_token_pkey PRIMARY KEY (id),
    CONSTRAINT uk_push_token_fid UNIQUE (fid)
);

-- 발송 때 회원의 FID 조회 · 회원당 상한 정리
CREATE INDEX idx_push_token_member_id ON notification.push_token (member_id, last_registered_at DESC);

-- 오래된 FID 정리
CREATE INDEX idx_push_token_last_registered_at ON notification.push_token (last_registered_at);
