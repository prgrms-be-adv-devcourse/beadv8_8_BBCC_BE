-- #601 주문 DLT(kidly.{product|seller|childprofile|payment}.events.order.dlt)에 들어간 메시지를 관리자가 확인 · 재처리 · 종료하도록
-- 저장한다. 원래 위치(토픽 · 파티션 · 오프셋)당 1건: 같은 메시지가 다시 오면 받은 횟수 · 마지막 받은 시각만 바꾼다.
-- 오래 지나도 이 행만 보고 판단할 수 있게 무슨 메시지(위치 · 키 · 헤더 · 원본 본문 · 본문 공통 칸) · 왜 실패(유형 · 예외 · 스택 앞부분)
-- · 어느 주문 · 언제 · 누가 무엇을(상태 · 처리자 · 메모 · 재처리 결과)을 남긴다. 본문 공통 칸 · 관련 주문은 읽지 못하면 null.
-- 주문 FK는 두지 않는다(다른 보관 표와 같음, 상품 · 판매자 · 자녀 이벤트는 주문이 없다). message_key는 Kafka 키(key는 예약어),
-- event_id는 헤더 값 그대로(UUID가 아닐 수 있음), handled_by는 처리한 관리자 회원 ID.
CREATE TABLE orders.order_dead_letter (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_topic character varying(100) NOT NULL,
    source_partition integer NOT NULL,
    source_offset bigint NOT NULL,
    message_key character varying(100),
    event_type character varying(60),
    event_id character varying(100),
    payload text,
    producer character varying(30),
    occurred_at timestamp(6) without time zone,
    aggregate_id character varying(100),
    correlation_id character varying(100),
    order_id bigint,
    failure_type character varying(20) NOT NULL,
    exception_class character varying(300),
    exception_message character varying(1000),
    stack_trace_head text,
    first_received_at timestamp(6) without time zone NOT NULL,
    last_received_at timestamp(6) without time zone NOT NULL,
    received_count integer NOT NULL,
    status character varying(20) NOT NULL,
    handled_by bigint,
    handled_at timestamp(6) without time zone,
    memo character varying(500),
    reprocess_count integer NOT NULL,
    last_reprocessed_at timestamp(6) without time zone,
    last_reprocess_result character varying(500),
    version bigint,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_order_dead_letter_source UNIQUE (source_topic, source_partition, source_offset),
    CONSTRAINT order_dead_letter_failure_type_check CHECK (((failure_type)::text = ANY ((ARRAY[
        'READ_FAILED'::character varying, 'STORE_FAILED'::character varying,
        'PROCESS_FAILED'::character varying])::text[]))),
    CONSTRAINT order_dead_letter_status_check CHECK (((status)::text = ANY ((ARRAY['OPEN'::character varying,
        'REPROCESSED'::character varying, 'CLOSED'::character varying])::text[]))),
    CONSTRAINT order_dead_letter_received_count_check CHECK (received_count >= 1),
    CONSTRAINT order_dead_letter_reprocess_count_check CHECK (reprocess_count >= 0)
);

-- 관리자 목록: 상태별(기본 OPEN) 최근 받은 것부터
CREATE INDEX idx_order_dead_letter_status ON orders.order_dead_letter USING btree (status, last_received_at);
