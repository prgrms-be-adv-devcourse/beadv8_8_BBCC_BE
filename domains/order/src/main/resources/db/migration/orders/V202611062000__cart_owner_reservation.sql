-- #998 장바구니 주인 일반화 · 칸 예약 · 주문상품의 장바구니 칸.
-- 주인(owner_type MEMBER · CHILD, owner_id = 회원 ID 또는 자녀 프로필 ID)을 더하고 기존 칸은 MEMBER + member_id로 옮긴다.
-- member_id는 그대로 둔다(자녀 주인이면 보호자 회원 ID). 같은 줄은 (주인, 옵션, 입을 자녀)로 바꾼다(자녀 칸과 보호자 칸이 member_id를 같이 써서).
-- 칸 예약: cart_reservation(예약 ID · 결제 허용 주체) + cart_item.reservation_id. 장바구니는 예약한 쪽을 모른다(예약 ID는 불투명 문자열).
-- 주문상품이 산 장바구니 칸(order_item.cart_item_id, 주문하기 요청에 준 경우만).
-- baseline 뒤 파일이라 이미 있는 DB에 다시 적용돼도 안전하게 둔다(OrderMigrationIntegrationTest)
ALTER TABLE orders.cart_item ADD COLUMN IF NOT EXISTS owner_type varchar(20);
ALTER TABLE orders.cart_item ADD COLUMN IF NOT EXISTS owner_id bigint;
ALTER TABLE orders.cart_item ADD COLUMN IF NOT EXISTS reservation_id varchar(64);
UPDATE orders.cart_item SET owner_type = 'MEMBER', owner_id = member_id WHERE owner_type IS NULL OR owner_id IS NULL;
ALTER TABLE orders.cart_item ALTER COLUMN owner_type SET NOT NULL;
ALTER TABLE orders.cart_item ALTER COLUMN owner_id SET NOT NULL;
ALTER TABLE orders.cart_item DROP CONSTRAINT IF EXISTS cart_item_owner_type_check;
ALTER TABLE orders.cart_item ADD CONSTRAINT cart_item_owner_type_check CHECK (owner_type IN ('MEMBER', 'CHILD'));
ALTER TABLE orders.cart_item DROP CONSTRAINT IF EXISTS uk_cart_item_member_option_child;
ALTER TABLE orders.cart_item DROP CONSTRAINT IF EXISTS uk_cart_item_owner_option_child;
ALTER TABLE orders.cart_item ADD CONSTRAINT uk_cart_item_owner_option_child UNIQUE (owner_type, owner_id, option_id, child_id);
CREATE INDEX IF NOT EXISTS idx_cart_item_reservation ON orders.cart_item (reservation_id);

CREATE TABLE IF NOT EXISTS orders.cart_reservation
(
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id varchar(64)                    NOT NULL,
    payer_type     varchar(20)                    NOT NULL,
    payer_id       bigint                         NOT NULL,
    created_at     timestamp(6) without time zone NOT NULL,
    updated_at     timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_cart_reservation_payer UNIQUE (reservation_id, payer_type, payer_id),
    CONSTRAINT cart_reservation_payer_type_check CHECK (payer_type IN ('MEMBER', 'CHILD'))
);

