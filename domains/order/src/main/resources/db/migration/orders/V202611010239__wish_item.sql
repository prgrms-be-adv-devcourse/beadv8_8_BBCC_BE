-- #640 조르기(부모 · 자녀 공용 장바구니) 줄. 같은 자녀(child_id = 자녀 프로필 ID)의 줄 목록이 그 자녀의 공용 장바구니다.
-- 담은 사람은 종류(PARENT · CHILD)와 ID(부모 = 회원 ID, 자녀 = 자녀 프로필 ID). 담은 시각은 created_at이다.
-- 같은 옵션을 합칠지는 정책이 정하므로(바꿀 수 있게) (자녀, 옵션) 유일 제약은 두지 않는다. 상태는 지금 ACTIVE 하나다.
-- 자녀 · 옵션 FK는 두지 않는다(다른 도메인 값, 장바구니와 같음). 걷어낼 때는 이 표를 지우는 마이그레이션을 추가한다.
CREATE TABLE orders.wish_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id bigint NOT NULL,
    option_id bigint NOT NULL,
    quantity integer NOT NULL,
    added_by_type character varying(20) NOT NULL,
    added_by_id bigint NOT NULL,
    status character varying(20) NOT NULL,
    version bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT wish_item_quantity_check CHECK (quantity >= 1),
    CONSTRAINT wish_item_added_by_type_check CHECK (((added_by_type)::text = ANY ((ARRAY['PARENT'::character varying,
        'CHILD'::character varying])::text[]))),
    CONSTRAINT wish_item_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying])::text[])))
);

-- 공용 장바구니 보기 · 같은 옵션 찾기 · 줄 수 세기: 자녀별 최근 담은 줄부터
CREATE INDEX idx_wish_item_child ON orders.wish_item USING btree (child_id, status, id);
