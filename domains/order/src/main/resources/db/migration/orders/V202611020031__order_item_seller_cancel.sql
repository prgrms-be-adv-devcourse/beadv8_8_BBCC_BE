-- #655 판매자 발송 전 부분 취소: 판매자가 READY인 자기 몫(배송 한 건)의 주문상품을 취소한다.
-- 주문상품: 상태에 CANCELLED를 더하고, 취소 사유 · 취소 기록 ID · 취소 시각을 둔다(취소되지 않았으면 null).
-- 주문: 모든 판매자 몫이 취소되면 주문도 취소되므로 취소 사유에 SELLER_CANCELLED를 더한다. 제약 이름은 그대로, 값만 늘린다.
-- 취소 기록: (주문, 판매자)당 한 건. ID가 이벤트 order-item.cancelled의 cancellationId다. 주문 FK는 두지 않는다(이력 표와 같음).
ALTER TABLE orders.order_item DROP CONSTRAINT order_item_status_check;

ALTER TABLE orders.order_item
    ADD CONSTRAINT order_item_status_check CHECK (((status)::text = ANY ((ARRAY['ORDERED'::character varying,
        'CONFIRMED'::character varying, 'CANCELLED'::character varying])::text[])));

ALTER TABLE orders.order_item
    ADD COLUMN cancel_reason character varying(30),
    ADD COLUMN cancellation_id bigint,
    ADD COLUMN cancelled_at timestamp(6) without time zone,
    ADD CONSTRAINT order_item_cancel_reason_check CHECK (((cancel_reason)::text = ANY ((ARRAY[
        'OUT_OF_STOCK'::character varying, 'WRONG_PRODUCT_INFO'::character varying,
        'OTHER'::character varying])::text[])));

ALTER TABLE orders.orders DROP CONSTRAINT orders_cancel_reason_check;

ALTER TABLE orders.orders
    ADD CONSTRAINT orders_cancel_reason_check CHECK (((cancel_reason)::text = ANY ((ARRAY[
        'OUT_OF_STOCK'::character varying, 'PAYMENT_FAILED'::character varying, 'PAYMENT_EXPIRED'::character varying,
        'BUYER_CANCELLED'::character varying, 'SELLER_CANCELLED'::character varying])::text[])));

CREATE TABLE orders.order_item_cancellation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    seller_id bigint NOT NULL,
    reason character varying(30) NOT NULL,
    memo character varying(500),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT order_item_cancellation_reason_check CHECK (((reason)::text = ANY ((ARRAY[
        'OUT_OF_STOCK'::character varying, 'WRONG_PRODUCT_INFO'::character varying,
        'OTHER'::character varying])::text[])))
);

CREATE UNIQUE INDEX uk_order_item_cancellation_order_seller ON orders.order_item_cancellation USING btree (order_id, seller_id);
