-- #926 멈춘 주문 AI 진단 메모. (주문, 멈춘 종류, 그때 마지막 상태 이력 ID)당 한 줄 = 상태가 바뀌기 전까지 한 번만 요청한다.
-- 실패(시간 초과 · 형식 오류 등)도 한 줄로 남긴다(같은 상태에서 다시 부르지 않고, 하루 요청 수에 센다).
-- baseline 뒤 파일이라 이미 있는 DB에 다시 적용돼도 안전하게 둔다(OrderMigrationIntegrationTest)
CREATE TABLE IF NOT EXISTS orders.order_stuck_diagnosis
(
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           bigint                         NOT NULL,
    stuck_kind         varchar(40)                    NOT NULL,
    history_mark       bigint                         NOT NULL,
    status             varchar(20)                    NOT NULL,
    summary            varchar(1000),
    recommended_action varchar(1000),
    confidence         varchar(10),
    failure_reason     varchar(40),
    provider           varchar(100)                   NOT NULL,
    model              varchar(100)                   NOT NULL,
    requested_at       timestamp(6) without time zone NOT NULL,
    created_at         timestamp(6) without time zone NOT NULL,
    updated_at         timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_order_stuck_diagnosis_state UNIQUE (order_id, stuck_kind, history_mark),
    CONSTRAINT order_stuck_diagnosis_status_check CHECK (status IN ('DIAGNOSED', 'FAILED')),
    CONSTRAINT order_stuck_diagnosis_confidence_check CHECK (confidence IS NULL OR confidence IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE INDEX IF NOT EXISTS idx_order_stuck_diagnosis_requested_at ON orders.order_stuck_diagnosis (requested_at);
