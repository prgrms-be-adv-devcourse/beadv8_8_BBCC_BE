-- #701 조르기 보내기 · 승인 · 거절. 조르기 한 건(wish_request)과 그 줄(wish_request_line)을 더하고,
-- 공용 장바구니 줄(wish_item)에 잠금(request_id = 진행 중인 조르기)과 결제돼 빠진 상태(PURCHASED)를 더한다. 기존 칸 · 값은 그대로다.
-- 자녀 · 옵션 · 주문 FK는 두지 않는다(다른 도메인 · 다른 컨텍스트 값). 걷어낼 때는 이 표들을 지우는 마이그레이션을 추가한다.
ALTER TABLE orders.wish_item ADD COLUMN request_id bigint;

ALTER TABLE orders.wish_item DROP CONSTRAINT wish_item_status_check;
ALTER TABLE orders.wish_item ADD CONSTRAINT wish_item_status_check
    CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'PURCHASED'::character varying])::text[])));

CREATE TABLE orders.wish_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id bigint NOT NULL,
    requested_by_type character varying(20) NOT NULL,
    requested_by_id bigint NOT NULL,
    message character varying(255),
    status character varying(20) NOT NULL,
    checkout character varying(20),
    order_id bigint,
    order_result character varying(20),
    reject_reason character varying(30),
    decided_by_id bigint,
    decided_at timestamp(6) without time zone,
    version bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT wish_request_requested_by_type_check CHECK (((requested_by_type)::text = ANY
        ((ARRAY['PARENT'::character varying, 'CHILD'::character varying])::text[]))),
    CONSTRAINT wish_request_status_check CHECK (((status)::text = ANY ((ARRAY['REQUESTED'::character varying,
        'APPROVED'::character varying, 'REJECTED'::character varying])::text[]))),
    CONSTRAINT wish_request_checkout_check CHECK (((checkout)::text = ANY
        ((ARRAY['ORDER'::character varying, 'CART'::character varying])::text[]))),
    CONSTRAINT wish_request_order_result_check CHECK (((order_result)::text = ANY
        ((ARRAY['PAID'::character varying, 'CANCELLED'::character varying])::text[]))),
    CONSTRAINT wish_request_reject_reason_check CHECK (((reject_reason)::text = ANY ((ARRAY[
        'TOO_EXPENSIVE'::character varying, 'ALREADY_HAVE'::character varying, 'NEXT_TIME'::character varying,
        'OTHER'::character varying])::text[])))
);

-- 자녀별 조르기 목록(최근부터) · 결제 결과를 기다리는 조르기 찾기
CREATE INDEX idx_wish_request_child ON orders.wish_request USING btree (child_id, id);

CREATE TABLE orders.wish_request_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL,
    wish_item_id bigint NOT NULL,
    option_id bigint NOT NULL,
    requested_quantity integer NOT NULL,
    approved_quantity integer,
    CONSTRAINT wish_request_line_requested_quantity_check CHECK (requested_quantity >= 1),
    CONSTRAINT wish_request_line_approved_quantity_check CHECK (approved_quantity >= 1),
    CONSTRAINT fk_wish_request_line_request FOREIGN KEY (request_id) REFERENCES orders.wish_request (id)
);

CREATE INDEX idx_wish_request_line_request ON orders.wish_request_line USING btree (request_id);
