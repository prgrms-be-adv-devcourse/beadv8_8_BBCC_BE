-- #1111 자녀가 지금 잘 맞게 입는 옷(기준 옷)의 구분, 세부 종류 카테고리, 실측을 저장하는 표를 만든다.
-- 자녀와 카테고리는 다른 도메인의 ID라 FK 없이 값으로만 둔다. 실측은 항목 코드를 키로, cm를 값으로 하는 JSON이다.
-- 같은 자녀의 같은 구분은 한 줄만 있고 다시 저장하면 그 줄을 바꾸므로 (child_profile_id, part)에 UNIQUE를 건다.
-- 회원 탈퇴 때 자녀 ID로 지우는 조회는 이 UNIQUE의 첫 칸 색인을 쓰므로 따로 색인을 만들지 않는다.
CREATE TABLE recommend.reference_garment (
    id bigint NOT NULL,
    child_profile_id bigint NOT NULL,
    part character varying(10) NOT NULL,
    category_id bigint NOT NULL,
    measurements jsonb NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE recommend.reference_garment ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME recommend.reference_garment_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY recommend.reference_garment
    ADD CONSTRAINT reference_garment_pkey PRIMARY KEY (id);

ALTER TABLE ONLY recommend.reference_garment
    ADD CONSTRAINT reference_garment_child_part_key UNIQUE (child_profile_id, part);
