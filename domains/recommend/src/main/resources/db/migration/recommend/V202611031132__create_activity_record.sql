-- #752 회원의 검색과 장바구니 담기를 한 줄씩 남기는 활동 기록 표를 만든다.
-- 활동 종류마다 쓰는 칸이 달라 종류에 해당하지 않는 칸은 null이다.
-- 같은 이벤트를 두 번 받아도 한 줄만 남도록 event_id에 UNIQUE를 건다.
CREATE TABLE recommend.activity_record (
    id bigint NOT NULL,
    event_id uuid NOT NULL,
    type character varying(30) NOT NULL,
    member_id bigint NOT NULL,
    child_profile_id bigint,
    occurred_at timestamp(6) without time zone NOT NULL,
    keyword text,
    category_id bigint,
    attribute_value_ids jsonb,
    result_count bigint,
    cart_item_id bigint,
    product_id bigint,
    product_option_id bigint,
    added_qty integer,
    cart_qty integer,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE recommend.activity_record ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME recommend.activity_record_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY recommend.activity_record
    ADD CONSTRAINT activity_record_pkey PRIMARY KEY (id);

ALTER TABLE ONLY recommend.activity_record
    ADD CONSTRAINT activity_record_event_id_key UNIQUE (event_id);
