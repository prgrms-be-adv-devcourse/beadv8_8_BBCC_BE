-- #730 Kafka 보존 기간과 무관하게 정산 DLT(kidly.order.events.settlement.dlt · kidly.payment.events.settlement.dlt) 원본을 보관한다.
-- DLT 토픽 · 파티션 · 오프셋당 1행. 관리자가 재처리하면 REPROCESSED가 되고 행은 지우지 않는다. 칸은 community.dead_letter와 같다.
CREATE TABLE settlement.settlement_dead_letter (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dlt_topic varchar(150) NOT NULL,
    dlt_partition integer NOT NULL,
    dlt_offset bigint NOT NULL,
    source_topic varchar(100) NOT NULL,
    source_partition integer,
    source_offset bigint,
    message_key varchar(100),
    event_type varchar(100),
    event_id varchar(100),
    payload bytea,
    failure_type varchar(255),
    state varchar(20) NOT NULL DEFAULT 'OPEN',
    replay_count integer NOT NULL DEFAULT 0,
    last_replayed_by bigint,
    last_replayed_at timestamp(6) without time zone,
    last_replay_failure_type varchar(255),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_settlement_dead_letter_position UNIQUE (dlt_topic, dlt_partition, dlt_offset),
    CONSTRAINT settlement_dead_letter_state_check CHECK (state IN ('OPEN', 'REPROCESSED')),
    CONSTRAINT settlement_dead_letter_replay_count_check CHECK (replay_count >= 0)
);

-- 관리자 목록: 상태별 최신순
CREATE INDEX idx_settlement_dead_letter_state_id ON settlement.settlement_dead_letter (state, id DESC);
