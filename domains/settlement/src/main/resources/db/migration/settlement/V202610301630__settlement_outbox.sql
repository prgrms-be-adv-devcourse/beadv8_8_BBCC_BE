-- 정산이 보내는 이벤트(settlement.payout-requested)를 Kafka로 보내기 전에 업무와 같은 트랜잭션에서 저장한다(아웃박스).
-- 업무가 롤백되면 메시지도 남지 않는다. 릴레이가 id 순서대로 안 보낸 행을 보내고 sent_at을 채운다. 보낸 행은 보관 기간(7일) 뒤 지운다.
-- 정산서 FK는 두지 않는다: 키(message_key)에 정산서 ID가 있고, 이벤트가 늘면 대상이 달라질 수 있다.
-- event_type은 헤더 eventType, message_key는 Kafka 메시지 키(key는 예약어), payload는 보낼 본문 JSON 그대로(text).
CREATE TABLE settlement.settlement_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL,
    event_type character varying(60) NOT NULL,
    topic character varying(100) NOT NULL,
    message_key character varying(100) NOT NULL,
    payload text NOT NULL,
    attempt_count integer NOT NULL,
    last_error character varying(500),
    sent_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_settlement_outbox_event_id UNIQUE (event_id),
    CONSTRAINT settlement_outbox_attempt_count_check CHECK (attempt_count >= 0)
);

-- 릴레이: 안 보낸 행을 id 순서로 읽는다
CREATE INDEX idx_settlement_outbox_unsent ON settlement.settlement_outbox USING btree (id) WHERE sent_at IS NULL;

-- 정리: 보낸 지 보관 기간이 지난 행을 지운다
CREATE INDEX idx_settlement_outbox_sent_at ON settlement.settlement_outbox USING btree (sent_at) WHERE sent_at IS NOT NULL;
