-- #729 빈 DB에서 kidly-app이 먼저 뜨면 kidly-app의 init이 정산 테이블을 만들지만, 아웃박스(V202610301630)와 유일 키 변경(V202611021248)은
-- 이제 정산 서비스에만 있어 적용되지 않는다. 그 뒤 서비스는 스키마가 비어 있지 않아 202611021248로 baseline을 잡고 두 파일을 건너뛴다.
-- 그런 DB에서만 두 파일과 같게 만든다. 이미 있는 DB에서는 아무것도 하지 않는다.
CREATE TABLE IF NOT EXISTS settlement.settlement_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL,
    event_type character varying(60) NOT NULL,
    topic character varying(100) NOT NULL,
    message_key character varying(100) NOT NULL,
    payload text NOT NULL,
    attempt_count integer NOT NULL,
    last_error character varying(500),
    sent_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_settlement_outbox_event_id UNIQUE (event_id),
    CONSTRAINT settlement_outbox_attempt_count_check CHECK (attempt_count >= 0)
);

CREATE INDEX IF NOT EXISTS idx_settlement_outbox_unsent ON settlement.settlement_outbox USING btree (id) WHERE sent_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_settlement_outbox_sent_at ON settlement.settlement_outbox USING btree (sent_at) WHERE sent_at IS NOT NULL;

-- 유일 키 (판매자, 종료일)가 없으면 옛 키 (판매자, 시작일, 종료일)를 지우고 만든다
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_settlement_seller_period_end_on') THEN
        ALTER TABLE settlement.settlement DROP CONSTRAINT IF EXISTS uk_settlement_seller_period;
        ALTER TABLE settlement.settlement ADD CONSTRAINT uk_settlement_seller_period_end_on UNIQUE (seller_id, period_end_on);
    END IF;
END
$$;
