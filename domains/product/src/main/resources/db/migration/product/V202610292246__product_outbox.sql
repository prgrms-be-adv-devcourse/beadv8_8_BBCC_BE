-- #551 상품이 보내는 이벤트를 Kafka로 보내기 전에 업무와 같은 트랜잭션에서 저장하는 아웃박스 표다.
-- 업무가 롤백되면 메시지도 남지 않는다. 릴레이가 id 순서대로 아직 보내지 않은 행을 Kafka로 보내고 sent_at을 채운다.
-- 보낸 행은 보관 기간이 지나면 삭제한다.
-- 상품 FK는 두지 않는다. 이벤트마다 대상이 상품이거나 주문으로 다르고, 대상 ID는 message_key에 들어 있다.
-- event_type은 헤더 eventType, message_key는 Kafka 메시지 키(key는 예약어), payload는 보낼 본문 JSON 그대로(text)다.
CREATE TABLE product.product_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL,
    event_type character varying(60) NOT NULL,
    topic character varying(100) NOT NULL,
    message_key character varying(100) NOT NULL,
    payload text NOT NULL,
    attempt_count integer NOT NULL,
    last_error character varying(500),
    sent_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_product_outbox_event_id UNIQUE (event_id),
    CONSTRAINT product_outbox_attempt_count_check CHECK (attempt_count >= 0)
);

-- 릴레이: 아직 보내지 않은 행을 id 순서로 읽는다
CREATE INDEX idx_product_outbox_unsent ON product.product_outbox USING btree (id) WHERE sent_at IS NULL;

-- 정리: 보낸 지 보관 기간이 지난 행을 지운다
CREATE INDEX idx_product_outbox_sent_at ON product.product_outbox USING btree (sent_at) WHERE sent_at IS NOT NULL;
