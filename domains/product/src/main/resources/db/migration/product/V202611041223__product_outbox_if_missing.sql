-- #791 kidly-app에서 상품 도메인을 빼면 빈 DB에서 kidly-app은 자기 폴더의 상품 파일(init · 기준 데이터 soft delete)까지만 적용한다.
-- 상품 서비스는 아웃박스 버전(202610292246)으로 baseline을 잡아 아웃박스 마이그레이션(V202610292246)을 건너뛰므로, 그런 DB에서만 아웃박스 표를 같은 모양으로 만든다.
-- 이미 있으면 아무것도 하지 않는다. kidly-app이 상품을 가진 동안에는 두 앱이 각자 이 파일을 적용하므로 두 번 적용돼도 안전하게 쓴다.
CREATE TABLE IF NOT EXISTS product.product_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL,
    event_type character varying(60) NOT NULL,
    topic character varying(100) NOT NULL,
    message_key character varying(100) NOT NULL,
    payload text NOT NULL,
    attempt_count integer NOT NULL,
    last_error character varying(500),
    sent_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_product_outbox_event_id UNIQUE (event_id),
    CONSTRAINT product_outbox_attempt_count_check CHECK (attempt_count >= 0)
);

CREATE INDEX IF NOT EXISTS idx_product_outbox_unsent ON product.product_outbox USING btree (id) WHERE sent_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_product_outbox_sent_at ON product.product_outbox USING btree (sent_at) WHERE sent_at IS NOT NULL;
