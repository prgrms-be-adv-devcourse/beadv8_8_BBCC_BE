-- 문서 분류와 답변 근거 조각(#1191). 문서를 저장하면 본문을 조각내 임베딩해 둔다
-- 문서는 아직 운영에 없지만 이미 적용된 DB를 생각해 기본값으로 채운 뒤 기본값을 지운다(새 행은 엔티티가 넣는다)
ALTER TABLE chatbot.knowledge_document ADD COLUMN category character varying(20) NOT NULL DEFAULT 'FAQ';
ALTER TABLE chatbot.knowledge_document ALTER COLUMN category DROP DEFAULT;

-- 임베딩은 pgvector 대신 real[]로 둔다. pgvector 확장은 추천 스키마에 있어 함께 쓰지 않고, 검색은 서버 메모리에서 한다
CREATE TABLE chatbot.knowledge_chunk (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    document_id bigint NOT NULL,
    seq integer NOT NULL,
    content text NOT NULL,
    embedding real[] NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT knowledge_chunk_pkey PRIMARY KEY (id),
    CONSTRAINT knowledge_chunk_document_fkey FOREIGN KEY (document_id)
        REFERENCES chatbot.knowledge_document (id) ON DELETE CASCADE,
    CONSTRAINT knowledge_chunk_document_seq_key UNIQUE (document_id, seq)
);
