-- #1390 환불하지 못한 주문상품 취소(order-item.cancelled)를 받은 내용 그대로 남겨 관리자가 다시 처리하거나 닫는다.
-- 취소마다 하나(cancellation_id UK). 환불되거나 관리자가 닫으면 지운다. 실패한 환불(refund FAILED)은 그대로 남는다
CREATE TABLE payment.order_item_cancellation_retry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cancellation_id bigint NOT NULL,
    order_id bigint NOT NULL,
    member_id bigint NOT NULL,
    reason character varying(255),
    attempt_count integer NOT NULL,
    last_error character varying(500),
    last_failed_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_order_item_cancellation_retry_cancellation_id UNIQUE (cancellation_id)
);

-- 취소된 주문상품과 환불할 금액. 기록을 지우면 함께 지운다
CREATE TABLE payment.order_item_cancellation_retry_item (
    retry_id bigint NOT NULL REFERENCES payment.order_item_cancellation_retry (id) ON DELETE CASCADE,
    order_item_id bigint NOT NULL,
    amount bigint NOT NULL
);

CREATE INDEX idx_order_item_cancellation_retry_item_retry_id
    ON payment.order_item_cancellation_retry_item USING btree (retry_id);
