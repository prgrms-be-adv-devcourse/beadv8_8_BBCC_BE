-- local · test · dev에서 토스 없이 넣은 개발용 예치금 기록(#1010). 원장 DEV_CHARGE의 ref_id가 이 표의 ID다.
-- 이 기록을 만드는 API는 prod에 등록되지 않아 prod에서는 표가 비어 있다.
CREATE TABLE payment.dev_charge (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id bigint NOT NULL,
    member_id bigint NOT NULL,
    amount bigint NOT NULL CHECK (amount > 0),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);
CREATE INDEX idx_dev_charge_wallet_id ON payment.dev_charge (wallet_id);

ALTER TABLE payment.wallet_ledger DROP CONSTRAINT wallet_ledger_type_check;
ALTER TABLE payment.wallet_ledger ADD CONSTRAINT wallet_ledger_type_check CHECK (type IN (
    'CHARGE', 'CHARGE_CANCEL', 'CHARGE_CANCEL_REVERT', 'PAYMENT', 'REFUND', 'SETTLEMENT', 'BALANCE_RETURN', 'DEV_CHARGE'));
