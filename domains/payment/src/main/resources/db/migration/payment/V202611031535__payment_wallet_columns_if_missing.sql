ALTER TABLE payment.wallet ADD COLUMN IF NOT EXISTS frozen_at timestamp(6) without time zone;

CREATE TABLE IF NOT EXISTS payment.balance_return (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id bigint NOT NULL,
    member_id bigint NOT NULL,
    amount bigint NOT NULL CHECK (amount > 0),
    returned_by bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_balance_return_wallet_id ON payment.balance_return (wallet_id);

ALTER TABLE payment.wallet_ledger DROP CONSTRAINT IF EXISTS wallet_ledger_type_check;
