-- 탈퇴 회원 지갑의 잔액 환급 기록(#731). 운영자가 시스템 밖에서 돌려줬다고 보고 잔액을 정리한다(실제 송금 없음).
-- 원장 BALANCE_RETURN의 ref_id가 이 표의 ID다. 환급 뒤 다시 입금되면 다시 환급할 수 있어 지갑마다 여러 건일 수 있다.
CREATE TABLE payment.balance_return (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id bigint NOT NULL,
    member_id bigint NOT NULL,
    amount bigint NOT NULL CHECK (amount > 0),
    returned_by bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);
CREATE INDEX idx_balance_return_wallet_id ON payment.balance_return (wallet_id);

ALTER TABLE payment.wallet_ledger DROP CONSTRAINT wallet_ledger_type_check;
ALTER TABLE payment.wallet_ledger ADD CONSTRAINT wallet_ledger_type_check CHECK (type IN (
    'CHARGE', 'CHARGE_CANCEL', 'CHARGE_CANCEL_REVERT', 'PAYMENT', 'REFUND', 'SETTLEMENT', 'BALANCE_RETURN'));
