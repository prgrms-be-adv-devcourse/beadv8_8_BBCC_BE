-- kidly-app의 같은 버전 init.sql에서 recommend 스키마 구문만 뽑았다(#704). 내용을 고치지 않는다
-- 이미 테이블이 있는 DB는 baseline(application.yml)으로 이 파일을 건너뛴다. 빈 DB(테스트)만 적용한다
-- 로컬은 kidly-app이 먼저 마이그레이션해야 한다. 빈 DB에서 이 서비스가 먼저 추천 테이블을 만들면 kidly-app의 init이 실패한다

CREATE SCHEMA IF NOT EXISTS recommend;

CREATE TABLE recommend.purchase_record (
    child_profile_id bigint NOT NULL,
    confirmed_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    member_id bigint NOT NULL,
    order_id bigint NOT NULL,
    order_item_id bigint NOT NULL,
    product_id bigint NOT NULL,
    product_option_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    size character varying(20) NOT NULL
);

ALTER TABLE recommend.purchase_record ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME recommend.purchase_record_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE recommend.replica_child (
    birth_date date NOT NULL,
    height_cm numeric(4,1) NOT NULL,
    weight_kg numeric(4,1) NOT NULL,
    child_profile_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    deleted_at timestamp(6) without time zone,
    event_occurred_at timestamp(6) without time zone NOT NULL,
    member_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    body_type character varying(255),
    gender character varying(255) NOT NULL,
    preferred_fit character varying(255),
    CONSTRAINT replica_child_body_type_check CHECK (((body_type)::text = ANY ((ARRAY['SLIM'::character varying, 'NORMAL'::character varying, 'CHUNKY'::character varying])::text[]))),
    CONSTRAINT replica_child_gender_check CHECK (((gender)::text = ANY ((ARRAY['MALE'::character varying, 'FEMALE'::character varying])::text[]))),
    CONSTRAINT replica_child_preferred_fit_check CHECK (((preferred_fit)::text = ANY ((ARRAY['SLIM'::character varying, 'REGULAR'::character varying, 'LOOSE'::character varying])::text[])))
);

CREATE TABLE recommend.replica_product (
    is_size_free boolean NOT NULL,
    category_id bigint,
    created_at timestamp(6) without time zone NOT NULL,
    event_occurred_at timestamp(6) without time zone NOT NULL,
    min_price bigint,
    product_id bigint NOT NULL,
    product_registered_at timestamp(6) without time zone NOT NULL,
    seller_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    name character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    thumbnail_url character varying(255),
    CONSTRAINT replica_product_status_check CHECK (((status)::text = ANY ((ARRAY['SALE_PENDING'::character varying, 'ON_SALE'::character varying, 'STOPPED'::character varying])::text[])))
);

CREATE TABLE recommend.replica_product_sellable_size (
    product_id bigint NOT NULL,
    size character varying(20) NOT NULL
);

CREATE TABLE recommend.replica_product_size (
    max_height_cm integer,
    min_height_cm integer,
    product_id bigint NOT NULL,
    size character varying(20) NOT NULL
);

CREATE TABLE recommend.replica_seller (
    created_at timestamp(6) without time zone NOT NULL,
    event_occurred_at timestamp(6) without time zone NOT NULL,
    seller_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    business_name character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    CONSTRAINT replica_seller_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'SUSPENDED'::character varying])::text[])))
);

ALTER TABLE ONLY recommend.purchase_record
    ADD CONSTRAINT purchase_record_order_item_id_key UNIQUE (order_item_id);

ALTER TABLE ONLY recommend.purchase_record
    ADD CONSTRAINT purchase_record_pkey PRIMARY KEY (id);

ALTER TABLE ONLY recommend.replica_child
    ADD CONSTRAINT replica_child_pkey PRIMARY KEY (child_profile_id);

ALTER TABLE ONLY recommend.replica_product
    ADD CONSTRAINT replica_product_pkey PRIMARY KEY (product_id);

ALTER TABLE ONLY recommend.replica_product_sellable_size
    ADD CONSTRAINT replica_product_sellable_size_pkey PRIMARY KEY (product_id, size);

ALTER TABLE ONLY recommend.replica_seller
    ADD CONSTRAINT replica_seller_pkey PRIMARY KEY (seller_id);

