-- #442 주문 상태 변경 이력: 주문 · 주문상품 · 배송 · 결제 복구 기록의 상태가 바뀔 때마다 한 줄씩 쌓는다(추가만, 수정 · 삭제 없음).
-- 주문 FK는 두지 않는다(배송 · 결제 복구 테이블과 같음): 결제 복구 기록은 주문 행을 바꾼 리스너 트랜잭션이 열려 있을 때
-- 다른 트랜잭션에서 저장되므로 주문 행 잠금과 엮일 여지를 없앤다. 관리자 조회는 주문별 시간순이라 (order_id, occurred_at, id) 인덱스.
-- 상태는 대상마다 enum이 달라 문자열로 둔다. reason은 결제 복구 failure_code(varchar(100))를 그대로 담는다.
CREATE TABLE orders.order_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    target_type character varying(20) NOT NULL,
    target_id bigint NOT NULL,
    from_status character varying(30),
    to_status character varying(30) NOT NULL,
    reason character varying(100),
    actor_type character varying(10) NOT NULL,
    actor_id bigint,
    source character varying(100) NOT NULL,
    occurred_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT order_status_history_target_type_check CHECK (((target_type)::text = ANY ((ARRAY[
        'ORDER'::character varying, 'ORDER_ITEM'::character varying, 'DELIVERY'::character varying,
        'PAYMENT_RECOVERY'::character varying])::text[]))),
    CONSTRAINT order_status_history_actor_type_check CHECK (((actor_type)::text = ANY ((ARRAY[
        'BUYER'::character varying, 'SELLER'::character varying, 'ADMIN'::character varying,
        'SYSTEM'::character varying, 'EVENT'::character varying])::text[])))
);

CREATE INDEX idx_order_status_history_order ON orders.order_status_history USING btree (order_id, occurred_at, id);
