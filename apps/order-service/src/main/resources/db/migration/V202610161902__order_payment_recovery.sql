-- #353 결제 완료 반영 실패 보관: 주문당 1건(order_id 유니크), 주문상품별 결제 금액은 자식 테이블.
-- 주문 FK는 두지 않는다(배송 테이블과 같음): 기록은 리스너 트랜잭션이 주문 행을 바꾼 채 열려 있을 때 다른 트랜잭션에서
-- 저장되므로, 주문 행 잠금과 엮일 여지를 없앤다. 주문당 1건은 order_id 유니크로 지킨다.
CREATE TABLE orders.payment_recovery (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    payment_id bigint,
    member_id bigint,
    amount bigint NOT NULL,
    status character varying(20) NOT NULL,
    failure_code character varying(100) NOT NULL,
    attempt_count integer NOT NULL,
    last_attempted_at timestamp(6) without time zone NOT NULL,
    version bigint,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT payment_recovery_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying,
        'RECOVERED'::character varying, 'CANCELLED'::character varying, 'NOT_RETRYABLE'::character varying])::text[])))
);

CREATE UNIQUE INDEX uk_payment_recovery_order ON orders.payment_recovery USING btree (order_id);

CREATE INDEX idx_payment_recovery_status ON orders.payment_recovery USING btree (status);

CREATE TABLE orders.payment_recovery_item (
    payment_recovery_id bigint NOT NULL,
    order_item_id bigint,
    amount bigint NOT NULL,
    CONSTRAINT fk_payment_recovery_item_recovery FOREIGN KEY (payment_recovery_id)
        REFERENCES orders.payment_recovery(id)
);
