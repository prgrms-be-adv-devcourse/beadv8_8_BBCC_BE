CREATE TABLE orders.orders (
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    member_id bigint NOT NULL,
    paid_at timestamp(6) without time zone,
    payment_due_at timestamp(6) without time zone NOT NULL,
    payment_id bigint,
    payment_requested_at timestamp(6) without time zone,
    total_amount bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    version bigint NOT NULL,
    cancel_reason character varying(20),
    status character varying(20) NOT NULL,
    address character varying(255),
    phone character varying(255),
    recipient_name character varying(255),
    zip_code character varying(255),
    CONSTRAINT orders_cancel_reason_check CHECK (((cancel_reason)::text = ANY ((ARRAY['OUT_OF_STOCK'::character varying, 'PAYMENT_FAILED'::character varying, 'PAYMENT_EXPIRED'::character varying])::text[]))),
    CONSTRAINT orders_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING_PAYMENT'::character varying, 'PAID'::character varying, 'CANCELLED'::character varying])::text[])))
