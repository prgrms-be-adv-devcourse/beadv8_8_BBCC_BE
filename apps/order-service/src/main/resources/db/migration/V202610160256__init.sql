-- kidly-app의 같은 버전 init.sql에서 orders 스키마 구문만 뽑았다. 내용을 고치지 않는다
-- 이미 테이블이 있는 DB는 baseline(application.yml)으로 이 파일을 건너뛴다. 빈 DB(테스트)만 적용한다
-- 로컬은 kidly-app이 먼저 마이그레이션해야 한다. 빈 DB에서 이 서비스가 먼저 주문 테이블을 만들면 kidly-app의 마이그레이션이 실패한다

CREATE SCHEMA IF NOT EXISTS orders;

CREATE TABLE orders.cart_item (
    quantity integer NOT NULL,
    child_id bigint,
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    member_id bigint NOT NULL,
    option_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    version bigint NOT NULL
);

