CREATE TABLE orders.delivery (
    created_at timestamp(6) without time zone NOT NULL,
    delivered_at timestamp(6) without time zone,
    id bigint NOT NULL,
    order_id bigint NOT NULL,
    seller_id bigint NOT NULL,
    shipped_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone NOT NULL,
    carrier character varying(20),
    status character varying(20) NOT NULL,
    tracking_number character varying(50),
    CONSTRAINT delivery_carrier_check CHECK (((carrier)::text = ANY ((ARRAY['CJ'::character varying, 'EPOST'::character varying, 'HANJIN'::character varying, 'LOTTE'::character varying, 'LOGEN'::character varying, 'DUMMY'::character varying])::text[]))),
    CONSTRAINT delivery_status_check CHECK (((status)::text = ANY ((ARRAY['READY'::character varying, 'SHIPPING'::character varying, 'DELIVERED'::character varying])::text[])))
);

ALTER TABLE orders.delivery ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
