    status character varying(20) NOT NULL,
    unavailable_reason character varying(50),
    body_type character varying(255),
    child_name character varying(255),
    option_name character varying(255),
    product_name character varying(255),
    size character varying(255),
    CONSTRAINT order_item_confirm_type_check CHECK (((confirm_type)::text = ANY ((ARRAY['DIRECT'::character varying, 'AUTO'::character varying])::text[]))),
    CONSTRAINT order_item_status_check CHECK (((status)::text = ANY ((ARRAY['ORDERED'::character varying, 'CONFIRMED'::character varying])::text[])))
