-- kidly-app의 같은 버전 init.sql에서 childprofile 스키마 구문만 뽑았다(#682). 내용을 고치지 않는다
-- 이미 테이블이 있는 DB는 baseline(application.yml)으로 이 파일을 건너뛴다. 빈 DB(테스트 · 새 로컬)만 적용한다

CREATE SCHEMA IF NOT EXISTS childprofile;

CREATE TABLE childprofile.child_profile (
    birth_date date NOT NULL,
    height_cm numeric(4,1) NOT NULL,
    weight_kg numeric(4,1) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    deleted_at timestamp(6) without time zone,
    id bigint NOT NULL,
    member_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    name character varying(50) NOT NULL,
    body_type character varying(255),
    gender character varying(255) NOT NULL,
    preferred_fit character varying(255),
    CONSTRAINT child_profile_body_type_check CHECK (((body_type)::text = ANY ((ARRAY['SLIM'::character varying, 'NORMAL'::character varying, 'CHUNKY'::character varying])::text[]))),
    CONSTRAINT child_profile_gender_check CHECK (((gender)::text = ANY ((ARRAY['MALE'::character varying, 'FEMALE'::character varying])::text[]))),
    CONSTRAINT child_profile_preferred_fit_check CHECK (((preferred_fit)::text = ANY ((ARRAY['SLIM'::character varying, 'REGULAR'::character varying, 'LOOSE'::character varying])::text[])))
);

ALTER TABLE childprofile.child_profile ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME childprofile.child_profile_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE childprofile.growth_record (
    height_cm numeric(4,1) NOT NULL,
    child_profile_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    recorded_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    body_type character varying(255),
    CONSTRAINT growth_record_body_type_check CHECK (((body_type)::text = ANY ((ARRAY['SLIM'::character varying, 'NORMAL'::character varying, 'CHUNKY'::character varying])::text[])))
);

ALTER TABLE childprofile.growth_record ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME childprofile.growth_record_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY childprofile.child_profile
    ADD CONSTRAINT child_profile_pkey PRIMARY KEY (id);

ALTER TABLE ONLY childprofile.growth_record
    ADD CONSTRAINT growth_record_pkey PRIMARY KEY (id);

CREATE INDEX idx_child_profile_member_id ON childprofile.child_profile USING btree (member_id);

CREATE INDEX idx_growth_record_child_profile_id ON childprofile.growth_record USING btree (child_profile_id);

ALTER TABLE ONLY childprofile.growth_record
    ADD CONSTRAINT fk_growth_record_child_profile FOREIGN KEY (child_profile_id) REFERENCES childprofile.child_profile(id);
