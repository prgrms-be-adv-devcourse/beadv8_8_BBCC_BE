-- 이미 테이블이 있는 DB는 baseline(application.yml)으로 이 파일을 건너뛴다. 빈 DB(테스트 · 새 로컬)만 적용한다

CREATE SCHEMA IF NOT EXISTS settlement;

CREATE TABLE settlement.settlement (
    fee_rate numeric(5,4) NOT NULL,
    period_end_on date NOT NULL,
    period_start_on date NOT NULL,
    completed_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    fee_amount bigint NOT NULL,
    id bigint NOT NULL,
    paid_at timestamp(6) without time zone,
    seller_id bigint NOT NULL,
    settlement_amount bigint NOT NULL,
    total_sales_amount bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    version bigint NOT NULL,
    status character varying(20) NOT NULL,
    fail_reason character varying(50),
    CONSTRAINT settlement_status_check CHECK (((status)::text = ANY ((ARRAY['COMPLETED'::character varying, 'PAID'::character varying, 'FAILED'::character varying])::text[])))
);

ALTER TABLE settlement.settlement ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME settlement.settlement_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE settlement.settlement_item (
    confirmed_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    order_id bigint NOT NULL,
    order_item_id bigint NOT NULL,
    sales_amount bigint NOT NULL,
    seller_id bigint NOT NULL,
    settlement_id bigint,
    updated_at timestamp(6) without time zone NOT NULL,
    version bigint NOT NULL,
    status character varying(20) NOT NULL,
    CONSTRAINT settlement_item_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'SETTLED'::character varying, 'EXCLUDED'::character varying])::text[])))
);

ALTER TABLE settlement.settlement_item ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME settlement.settlement_item_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY settlement.settlement_item
    ADD CONSTRAINT settlement_item_pkey PRIMARY KEY (id);

ALTER TABLE ONLY settlement.settlement
    ADD CONSTRAINT settlement_pkey PRIMARY KEY (id);

ALTER TABLE ONLY settlement.settlement_item
    ADD CONSTRAINT uk_settlement_item_order_item_id UNIQUE (order_item_id);

ALTER TABLE ONLY settlement.settlement
    ADD CONSTRAINT uk_settlement_seller_period UNIQUE (seller_id, period_start_on, period_end_on);

CREATE INDEX idx_settlement_item_seller_status_confirmed ON settlement.settlement_item USING btree (seller_id, status, confirmed_at);

CREATE INDEX idx_settlement_item_settlement_id ON settlement.settlement_item USING btree (settlement_id);

