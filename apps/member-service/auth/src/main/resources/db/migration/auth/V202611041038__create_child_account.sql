-- 자녀 계정. 자녀 프로필 하나에 계정 하나다. 다른 스키마를 참조하지 않는다
CREATE TABLE auth.child_account (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id         varchar(20)  NOT NULL,
    password_hash    varchar(100) NOT NULL,
    guardian_id      bigint       NOT NULL,
    child_profile_id bigint       NOT NULL,
    created_at       timestamp(6) NOT NULL,
    updated_at       timestamp(6) NOT NULL,
    CONSTRAINT uk_child_account_login_id UNIQUE (login_id),
    CONSTRAINT uk_child_account_child_profile_id UNIQUE (child_profile_id)
);
