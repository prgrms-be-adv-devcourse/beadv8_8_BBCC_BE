-- 관리자 계정. 회원과 ID 공간이 다르다. 다른 스키마를 참조하지 않는다
CREATE TABLE auth.admin_account (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(255) NOT NULL,
    password_hash varchar(100) NOT NULL,
    status        varchar(20)  NOT NULL,
    created_by    bigint,
    created_at    timestamp(6) NOT NULL,
    updated_at    timestamp(6) NOT NULL,
    CONSTRAINT uk_admin_account_email UNIQUE (email),
    CONSTRAINT admin_account_status_check CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- 첫 관리자(created_by가 비어 있는 행)는 하나뿐이다. 서로 다른 이메일로 두 인스턴스가 동시에 떠도 DB가 막는다
CREATE UNIQUE INDEX uk_admin_account_bootstrap ON auth.admin_account ((true)) WHERE created_by IS NULL;
