CREATE TABLE seller.seller_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL,
    event_type character varying(60) NOT NULL,
    topic character varying(100) NOT NULL,
    message_key character varying(100) NOT NULL,
    payload text NOT NULL,
    attempt_count integer NOT NULL,
    last_error character varying(500),
    sent_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_seller_outbox_event_id UNIQUE (event_id),
    CONSTRAINT seller_outbox_attempt_count_check CHECK (attempt_count >= 0)
);

CREATE INDEX idx_seller_outbox_unsent ON seller.seller_outbox USING btree (id) WHERE sent_at IS NULL;

CREATE INDEX idx_seller_outbox_sent_at ON seller.seller_outbox USING btree (sent_at) WHERE sent_at IS NOT NULL;
