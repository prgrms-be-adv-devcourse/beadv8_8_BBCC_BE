-- kidly-app의 같은 버전 init.sql에서 member · seller 스키마 구문만 뽑았다. 내용을 고치지 않는다
-- 이미 테이블이 있는 DB는 baseline(MemberFlywayMigrationStrategy)으로 이 파일을 건너뛴다. 빈 DB(테스트 · 새 로컬)만 적용한다

CREATE SCHEMA IF NOT EXISTS member;

CREATE SCHEMA IF NOT EXISTS seller;

CREATE TABLE member.default_shipping_address (
    created_at timestamp(6) without time zone NOT NULL,
    member_id bigint NOT NULL,
    shipping_address_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE member.member (
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    seller_status_changed_at timestamp(6) without time zone,
    suspended_at timestamp(6) without time zone,
    suspended_by bigint,
    updated_at timestamp(6) without time zone NOT NULL,
    suspend_reason character varying(200),
    email character varying(255),
    nickname character varying(255) NOT NULL,
    role character varying(255) NOT NULL,
    seller_status character varying(255),
    status character varying(255) NOT NULL,
    CONSTRAINT member_role_check CHECK (((role)::text = ANY ((ARRAY['USER'::character varying, 'ADMIN'::character varying])::text[]))),
    CONSTRAINT member_seller_status_check CHECK (((seller_status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'SUSPENDED'::character varying])::text[]))),
    CONSTRAINT member_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'SUSPENDED'::character varying, 'WITHDRAWN'::character varying])::text[])))
);

ALTER TABLE member.member ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME member.member_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE member.refresh_token (
    created_at timestamp(6) without time zone NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    member_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    token_hash character varying(64) NOT NULL
);

CREATE TABLE member.shipping_address (
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    member_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    zip_code character varying(10) NOT NULL,
    recipient_phone character varying(13) NOT NULL,
    recipient_name character varying(50) NOT NULL,
    detail_address character varying(100),
    road_address character varying(200) NOT NULL
);

ALTER TABLE member.shipping_address ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME member.shipping_address_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE member.social_account (
    connected_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    member_id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    provider character varying(255) NOT NULL,
    provider_user_id character varying(255) NOT NULL,
    CONSTRAINT social_account_provider_check CHECK (((provider)::text = 'KAKAO'::text))
);

ALTER TABLE member.social_account ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME member.social_account_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE seller.seller (
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    suspended_at timestamp(6) without time zone,
    suspended_by bigint,
    updated_at timestamp(6) without time zone NOT NULL,
    version bigint NOT NULL,
    business_name character varying(50) NOT NULL,
    suspend_reason character varying(200),
    status character varying(255) NOT NULL,
    CONSTRAINT seller_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'SUSPENDED'::character varying])::text[])))
);

CREATE TABLE seller.seller_application (
    applicant_id bigint NOT NULL,
    applicant_nickname_changed_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    decided_at timestamp(6) without time zone,
    decided_by bigint,
    id bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    version bigint NOT NULL,
    business_registration_number character varying(10) NOT NULL,
    business_name character varying(50) NOT NULL,
    representative_name character varying(50) NOT NULL,
    reject_reason character varying(200),
    applicant_nickname character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    CONSTRAINT seller_application_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'APPROVED'::character varying, 'REJECTED'::character varying])::text[])))
);

ALTER TABLE seller.seller_application ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME seller.seller_application_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

