CREATE TABLE childprofile.child_consent (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_profile_id bigint NOT NULL,
    consenter varchar(255) NOT NULL CHECK (consenter IN ('GUARDIAN')),
    has_optional_consent boolean NOT NULL,
    consented_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT fk_child_consent_child_profile FOREIGN KEY (child_profile_id) REFERENCES childprofile.child_profile(id)
);

CREATE INDEX idx_child_consent_child_profile_id ON childprofile.child_consent (child_profile_id);
