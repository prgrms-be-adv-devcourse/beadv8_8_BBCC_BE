-- #682 빈 DB에서 kidly-app이 먼저 뜨면 kidly-app의 init이 자녀 테이블을 만들지만, 아웃박스(V202610300953)는 이제 자녀 프로필 서비스에만 있어
-- 만들어지지 않는다. 그 뒤 서비스는 스키마가 비어 있지 않아 202610300953으로 baseline을 잡고 아웃박스를 건너뛴다.
-- 그런 DB에서만 아웃박스를 V202610300953과 같게 만든다. 이미 있는 DB에서는 아무것도 하지 않는다.
CREATE TABLE IF NOT EXISTS childprofile.child_profile_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL,
    event_type character varying(60) NOT NULL,
    topic character varying(100) NOT NULL,
    message_key character varying(100) NOT NULL,
    payload text NOT NULL,
    attempt_count integer NOT NULL,
    last_error character varying(500),
    sent_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_child_profile_outbox_event_id UNIQUE (event_id),
    CONSTRAINT child_profile_outbox_attempt_count_check CHECK (attempt_count >= 0)
);

CREATE INDEX IF NOT EXISTS idx_child_profile_outbox_unsent ON childprofile.child_profile_outbox USING btree (id) WHERE sent_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_child_profile_outbox_sent_at ON childprofile.child_profile_outbox USING btree (sent_at) WHERE sent_at IS NOT NULL;
