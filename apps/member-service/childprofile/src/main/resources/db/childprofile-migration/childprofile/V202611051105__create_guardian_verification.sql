CREATE TABLE childprofile.guardian_verification (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    identity_key varchar(64) NOT NULL,
    birth_date date NOT NULL,
    verified_at timestamp(6) without time zone NOT NULL,
    identity_verification_id varchar(255) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_guardian_verification_member_id UNIQUE (member_id),
    CONSTRAINT uk_guardian_verification_identity_key UNIQUE (identity_key),
    CONSTRAINT uk_guardian_verification_identity_verification_id UNIQUE (identity_verification_id)
);
