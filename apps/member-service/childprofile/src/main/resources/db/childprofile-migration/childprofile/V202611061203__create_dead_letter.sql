CREATE TABLE childprofile.dead_letter (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dlt_topic varchar(150) NOT NULL,
    dlt_partition integer NOT NULL,
    dlt_offset bigint NOT NULL,
    source_topic varchar(100) NOT NULL,
    source_partition integer,
    source_offset bigint,
    message_key varchar(100),
    event_type varchar(100),
    event_id varchar(100),
    payload bytea,
    failure_type varchar(255),
    status varchar(20) NOT NULL DEFAULT 'OPEN',
    replay_count integer NOT NULL DEFAULT 0,
    last_replayed_by bigint,
    last_replayed_at timestamp(6) without time zone,
    last_replay_failure_type varchar(255),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_childprofile_dead_letter_position UNIQUE (dlt_topic, dlt_partition, dlt_offset),
    CONSTRAINT childprofile_dead_letter_status_check CHECK (status IN ('OPEN', 'REPROCESSED')),
    CONSTRAINT childprofile_dead_letter_replay_count_check CHECK (replay_count >= 0)
);

CREATE INDEX idx_childprofile_dead_letter_status_id ON childprofile.dead_letter (status, id DESC);
